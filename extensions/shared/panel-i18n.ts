const keys = Object.keys(english).sort((a, b) => b.length - a.length);
const pattern = new RegExp(keys.map(key => key.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')).join('|'), 'g');

export class PanelI18n {
  locale: PanelLocale = 'zh';
  text = (source: string): string => this.locale === 'en' ? source.replace(pattern, key => english[key]!) : source;
  html = (strings: TemplateStringsArray, ...values: unknown[]): string => strings.reduce((result, part, index) => result + this.text(part) + (index < values.length ? String(values[index] ?? '') : ''), '');
}
